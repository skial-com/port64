# Writes git_version.cpp, which defines the strings smsdk_config.h points
# SMEXT_CONF_VERSION and SMEXT_CONF_DATESTRING at: SMEXT_CONF_BASE_VERSION plus
# the short commit hash (with -dirty for uncommitted changes), and the time of
# this build.
#
# It also writes a make-style dependency file listing HEAD's reflog and every
# file in the repo, so AMBuild reruns it after a commit, checkout or edit and
# the hash and date never go stale the way __DATE__ does in smsdk_ext.cpp.
#
# usage: git_version.py <source dir> <build dir> <output .cpp> <output .d>
import os, subprocess, sys, time

def git(source_dir, *args):
  try:
    return subprocess.check_output(['git', '-C', source_dir] + list(args),
                                   stderr = subprocess.DEVNULL).decode('utf-8')
  except (OSError, subprocess.CalledProcessError):
    return None

def make_escape(path):
  return path.replace('\\', '\\\\').replace(' ', '\\ ').replace('#', '\\#').replace('$', '$$')

def main():
  source_dir, build_dir, out_cpp, out_deps = sys.argv[1:5]
  build_dir = os.path.join(os.path.abspath(build_dir), '')

  head = git(source_dir, 'rev-parse', '--short', 'HEAD')
  if head is None:
    version = 'nogit'
    deps = []
  else:
    version = head.strip()
    if git(source_dir, 'status', '--porcelain'):
      version += '-dirty'

    top = git(source_dir, 'rev-parse', '--show-toplevel').strip()
    files = git(source_dir, 'ls-files', '-z', '--cached', '--others', '--exclude-standard')
    deps = [os.path.join(top, f) for f in files.split('\0') if f]
    for ref in ['logs/HEAD', 'HEAD']:
      path = git(source_dir, 'rev-parse', '--path-format=absolute', '--git-path', ref)
      if path:
        deps.append(path.strip())
    # A build folder inside the repo that .gitignore misses would otherwise make
    # this script depend on its own output.
    deps = [d for d in deps
            if os.path.isfile(d) and not os.path.abspath(d).startswith(build_dir)]

  date = time.strftime('%Y-%m-%d %H:%M:%S %Z')

  with open(out_cpp, 'w') as fp:
    fp.write('// Generated by git_version.py; do not edit.\n')
    fp.write('#include "smsdk_config.h"\n\n')
    fp.write('extern const char g_ExtVersion[] = SMEXT_CONF_BASE_VERSION "-{}";\n'.format(version))
    fp.write('extern const char g_ExtBuildDate[] = "{}";\n'.format(date))

  with open(out_deps, 'w') as fp:
    fp.write('{}: \\\n'.format(make_escape(out_cpp)))
    for d in deps:
      fp.write('  {} \\\n'.format(make_escape(d)))
    fp.write('\n')

if __name__ == '__main__':
  main()
